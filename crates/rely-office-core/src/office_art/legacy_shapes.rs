/// The outline of a shape type drawn from its own geometry in a frame of this size, with the
/// adjust values the shape sets, an unset one taking the type's default; `None` for a type
/// drawn from a preset.
#[must_use]
pub(crate) fn legacy_shape_paths(
    kind: u16,
    adjust: &[Option<i64>; 10],
    width: i64,
    height: i64,
) -> Option<Vec<ShapePath>> {
    let shape = legacy_shape(kind)?;
    let mut freeform = Freeform {
        degrees: true,
        stretch: (shape.stretch, shape.stretch),
        shades: shape.shades,
        vertices: shape
            .vertices
            .iter()
            .map(|(x, y)| (coordinate(*x, true), coordinate(*y, true)))
            .collect(),
        segments: shape.segments.to_vec(),
        guides: shape
            .guides
            .iter()
            .map(|(operation, parameters)| Guide {
                operation: *operation,
                parameters: *parameters,
            })
            .collect(),
        ..Freeform::default()
    };
    for (index, value) in freeform.adjust.iter_mut().enumerate() {
        *value = match adjust[index] {
            #[expect(clippy::cast_precision_loss, reason = "adjust values are small")]
            Some(set) => {
                let set = set as f64;
                // A file keeps the circular arrow's two angles in 16.16 degrees.
                if kind == 99 && index < 2 {
                    set / 65_536.0
                } else {
                    set
                }
            }
            None => shape.defaults.get(index).copied().unwrap_or(0.0),
        };
    }
    freeform.paths(width, height)
}

