//! The old shape types whose outline no `DrawingML` preset draws the same, with their own
//! geometry: the bent, curved, circular and U-turn arrows, the quad arrow callout, the
//! elliptical ribbons and the action buttons. Each is vertices in a space of 21,600 units, the
//! segments that join them and the guide formulas that place them from the adjust values, as
//! `PowerPoint` 97 and `Word` 97 draw them. Taken from the tables of `LibreOffice`
//! (`svx/source/customshapes/EnhancedCustomShapeGeometry.cxx`, MPL-2.0), whose angles are in
//! degrees.

use super::freeform::{Freeform, Guide, coordinate};
use crate::geometry::ShapePath;

/// The geometry of one shape type.
struct LegacyShape {
    /// Coordinates, a guide named as `0x8000_0000` and its index.
    vertices: &'static [(i64, i64)],
    segments: &'static [u16],
    guides: &'static [(u16, [i32; 3])],
    defaults: &'static [f64],
    /// Whether the shape keeps its picture square in a frame that is not.
    stretch: bool,
    /// The luminance of each filled path, as [`Freeform::shades`].
    shades: u32,
}

